-- Run this entire script in Supabase Dashboard → SQL Editor.
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null,
  standard text not null,
  school text not null,
  status text not null default 'registered' check (status in ('registered','confirmed','active','completed','withdrawn')),
  created_at timestamptz not null default now()
);
create index if not exists students_created_at_idx on public.students(created_at desc);
create index if not exists students_email_idx on public.students(lower(email));
create table if not exists public.student_records (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  record_date date not null default current_date,
  record_type text not null default 'progress' check (record_type in ('progress','assessment','project','mentor_note')),
  attendance text check (attendance in ('Present','Absent','Late','Leave')),
  topic text,
  activities text,
  attempts text,
  learning_interest text,
  assessment_score integer check (assessment_score between 0 and 100),
  trainer_remarks text,
  next_steps text,
  created_at timestamptz not null default now()
);
create index if not exists student_records_student_date_idx on public.student_records(student_id,record_date desc);
-- Keep tables private. The Flask server uses the Supabase service-role key, which bypasses RLS.
alter table public.students enable row level security;
alter table public.student_records enable row level security;
